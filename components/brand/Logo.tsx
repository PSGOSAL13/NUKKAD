import { cn } from "@/lib/cn";
import { logoManifest } from "./logo-manifest";

type Variant = "primary" | "primary-tagline" | "secondary" | "symbol";
type Tone = "full" | "reverse" | "mono-ink" | "mono-cream";

type LogoProps = {
  variant?: Variant;
  /** full = on cream/light · reverse = on deep red · mono-* = single colour */
  tone?: Tone;
  /** Rendered height in px; width follows the logo's proportions. */
  height: number;
  /** Use when the logo sits next to visible text that already names the café. */
  decorative?: boolean;
  priority?: boolean;
  className?: string;
};

/**
 * NUKKAD logo. Files are generated by `npm run brand:logos` into /public/brand.
 * Plain <img>: no JS, cached by the browser, and the intrinsic size is known
 * so the layout never jumps.
 */
export function Logo({
  variant = "secondary",
  tone = "full",
  height,
  decorative,
  priority,
  className,
}: LogoProps) {
  const name = `nukkad-${variant}-${tone}` as keyof typeof logoManifest;
  const size = logoManifest[name];
  const width = Math.round((size.width / size.height) * height);
  return (
    // eslint-disable-next-line @next/next/no-img-element -- static SVG; next/image adds nothing here
    <img
      src={`/brand/${name}.svg`}
      width={width}
      height={height}
      alt={decorative ? "" : "NUKKAD | नुक्कड"}
      fetchPriority={priority ? "high" : undefined}
      loading={priority ? "eager" : "lazy"}
      decoding="async"
      className={cn("select-none", className)}
    />
  );
}
